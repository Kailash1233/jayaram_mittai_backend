-- Admin delivery management. Additive only: safe to run before or after
-- deploying the backend that uses it.

-- deliveryzones.id has no default, so admin-created zones can't be inserted.
-- Number new zones automatically, continuing after the existing ones.
ALTER TABLE public.deliveryzones
  ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;

SELECT setval(
  pg_get_serial_sequence('public.deliveryzones', 'id'),
  COALESCE((SELECT MAX(id) FROM public.deliveryzones), 0) + 1,
  false
);

-- Shop operating hours: a weekly schedule (day_of_week 0=Sun … 6=Sat)
-- plus date-specific overrides (holidays, extended hours).
CREATE TABLE IF NOT EXISTS public.delivery_hours (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day_of_week   smallint CHECK (day_of_week BETWEEN 0 AND 6),
  override_date date,
  open_time     time,
  close_time    time,
  is_closed     boolean NOT NULL DEFAULT false,
  note          text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  -- Each entry is either a weekday or a specific date, never both
  CONSTRAINT delivery_hours_day_or_date
    CHECK ((day_of_week IS NULL) <> (override_date IS NULL)),
  -- An open day needs both times
  CONSTRAINT delivery_hours_times_when_open
    CHECK (is_closed OR (open_time IS NOT NULL AND close_time IS NOT NULL))
);

-- At most one entry per weekday and one per date, so the hours are unambiguous
CREATE UNIQUE INDEX IF NOT EXISTS delivery_hours_day_of_week_key
  ON public.delivery_hours (day_of_week) WHERE day_of_week IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS delivery_hours_override_date_key
  ON public.delivery_hours (override_date) WHERE override_date IS NOT NULL;

-- No policies: only the backend's secret-key (admin) client can access it
ALTER TABLE public.delivery_hours ENABLE ROW LEVEL SECURITY;
